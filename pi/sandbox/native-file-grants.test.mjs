import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { SandboxManager } from "@anthropic-ai/sandbox-runtime";
import { validateFilesystemGrants } from "./filesystem-grants.mjs";
import { buildSrtPolicy } from "./srt-policy.mjs";

test("native single-file grants isolate siblings and inherit in descendants", { timeout: 30000 }, async (t) => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "pi-native-file-grants-")));
  const home = path.join(root, "home"), workspaceRoot = path.join(root, "workspace"), controllerRoot = path.join(root, "controller"), broker = path.join(root, "broker"), files = path.join(home, "fixtures");
  for (const dir of [files, workspaceRoot, controllerRoot, broker]) fs.mkdirSync(dir, { recursive: true });
  const ro = path.join(files, "read only"), rw = path.join(files, "read write"), sibling = path.join(files, "sibling"), alias = path.join(home, "file-alias"), temporary = path.join(files, "temporary");
  fs.writeFileSync(ro, "readonly bytes"); fs.writeFileSync(rw, "original bytes"); fs.writeFileSync(sibling, "sibling bytes"); fs.symlinkSync(ro, alias);
  const renameSource = path.join(workspaceRoot, "rename-source"); fs.writeFileSync(renameSource, "renamed bytes");
  const dockerSocket = path.join(broker, "docker.sock"); fs.writeFileSync(dockerSocket, "");
  const options = { home, workspaceRoot, controllerRoot, dockerSocket };
  const grants = validateFilesystemGrants([{ path: alias, access: "ro" }, { path: rw, access: "rw" }], options);
  const policy = buildSrtPolicy({ ...options, grants });
  assert(!policy.filesystem.allowRead.includes(files));
  assert(!policy.filesystem.allowWrite.includes(files));
  const oldCwd = process.cwd(); let initialized = false;
  t.after(async () => { process.chdir(oldCwd); if (initialized) await SandboxManager.reset(); fs.rmSync(root, { recursive: true, force: true }); });
  process.chdir(workspaceRoot);
  await SandboxManager.initialize(policy, async () => true); initialized = true;
  const probe = `const fs=require('node:fs'), cp=require('node:child_process');
const [ro,rw,sibling,alias,parent,temp,renameSource]=process.argv.slice(1);
const attempt=fn=>{try{return {value:fn()}}catch(e){return {error:e.code}}};
const read=p=>attempt(()=>fs.readFileSync(p,'utf8'));
const inplace=(p,s)=>attempt(()=>{const fd=fs.openSync(p,'r+');try{fs.writeSync(fd,s,0,'utf8')}finally{fs.closeSync(fd)}return 'written'});
const child=cp.execFileSync(process.execPath,['-e',"const fs=require('node:fs');for(const p of process.argv.slice(1)){try{console.log(JSON.stringify({value:fs.readFileSync(p,'utf8')}))}catch(e){console.log(JSON.stringify({error:e.code}))}}",alias,sibling],{encoding:'utf8'}).trim().split('\\n').map(l=>JSON.parse(l));
const result={ro:read(ro),alias:read(alias),rw:read(rw),sibling:read(sibling),parent:attempt(()=>fs.readdirSync(parent)),roWrite:inplace(ro,'X'),rwWrite:inplace(rw,'UPDATED bytes!'),siblingWrite:inplace(sibling,'X'),child};
result.create=attempt(()=>fs.writeFileSync(temp,'temporary',{flag:'wx'}));
result.rename=attempt(()=>{fs.renameSync(renameSource,rw);return 'renamed'});
console.log(JSON.stringify(result));`;
  const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;
  const wrapped = await SandboxManager.wrapWithSandbox([process.execPath, "-e", probe, ro, rw, sibling, alias, files, temporary, renameSource].map(quote).join(" "), "sh");
  const result = spawnSync("/bin/sh", ["-lc", wrapped], { cwd: workspaceRoot, encoding: "utf8", env: { HOME: workspaceRoot, PATH: process.env.PATH, TMPDIR: os.tmpdir() } });
  assert.equal(result.status, 0, result.stderr);
  const evidence = JSON.parse(result.stdout);
  assert.deepEqual(evidence.ro, { value: "readonly bytes" });
  assert.deepEqual(evidence.alias, { value: "readonly bytes" });
  assert.deepEqual(evidence.rw, { value: "original bytes" });
  for (const denied of [evidence.sibling, evidence.parent, evidence.roWrite, evidence.siblingWrite, evidence.create, evidence.child[1]]) assert.match(denied.error, /^(EPERM|EACCES)$/);
  assert.deepEqual(evidence.child[0], { value: "readonly bytes" });
  assert.deepEqual(evidence.rwWrite, { value: "written" });
  assert.equal(fs.readFileSync(ro, "utf8"), "readonly bytes");
  if (evidence.rename.error) assert.match(evidence.rename.error, /^(EPERM|EACCES|EXDEV|EROFS)$/);
  else assert.equal(evidence.rename.value, "renamed");
  assert.equal(fs.readFileSync(rw, "utf8"), evidence.rename.error ? "UPDATED bytes!" : "renamed bytes");
  assert.equal(fs.readFileSync(sibling, "utf8"), "sibling bytes");
  assert.equal(fs.existsSync(temporary), false);
  console.log(JSON.stringify({ nativeFileGrantEvidence: evidence }));
});
