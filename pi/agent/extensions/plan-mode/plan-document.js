function error(code, message, line) {
	return { code, message, ...(line ? { line } : {}) };
}

function contentBetween(lines, start, end) {
	return lines.slice(start, end).join("\n").trim();
}

function scanHeadings(lines) {
	const headings = [];
	let fence = null;
	for (let index = 0; index < lines.length; index += 1) {
		const line = lines[index];
		const fenceMatch = line.match(/^\s*(`{3,}|~{3,})/);
		if (fenceMatch) {
			const marker = fenceMatch[1][0];
			if (fence === null) fence = marker;
			else if (fence === marker) fence = null;
			continue;
		}
		if (fence !== null) continue;
		const match = line.match(/^(#{1,6})\s+(.+?)\s*$/);
		if (match) headings.push({ level: match[1].length, text: match[2], index, line: index + 1 });
	}
	return headings;
}

function unfencedLineRows(content, startLine = 1) {
	const rows = content.split("\n").map((line, offset) => ({ line, number: startLine + offset }));
	const result = [];
	let fence = null;
	for (const row of rows) {
		const fenceMatch = row.line.match(/^\s*(`{3,}|~{3,})/);
		if (fenceMatch) {
			const marker = fenceMatch[1][0];
			if (fence === null) fence = marker;
			else if (fence === marker) fence = null;
			continue;
		}
		if (fence === null) result.push(row);
	}
	return result;
}

function unfencedTableBlocks(content, startLine) {
	const blocks = [];
	let current = [];
	for (const row of unfencedLineRows(content, startLine)) {
		if (row.line.trim().startsWith("|") && (current.length === 0 || row.number === current.at(-1).number + 1)) {
			current.push(row);
			continue;
		}
		if (current.length > 0) blocks.push(current);
		current = row.line.trim().startsWith("|") ? [row] : [];
	}
	if (current.length > 0) blocks.push(current);
	return blocks;
}

function splitTableRow(line) {
	const trimmed = line.trim();
	if (!trimmed.startsWith("|") || !trimmed.endsWith("|")) return null;
	const cells = [];
	let value = "";
	let escaped = false;
	for (const character of trimmed.slice(1, -1)) {
		if (escaped) {
			value += character;
			escaped = false;
		} else if (character === "\\") {
			escaped = true;
		} else if (character === "|") {
			cells.push(value.trim());
			value = "";
		} else {
			value += character;
		}
	}
	if (escaped) value += "\\";
	cells.push(value.trim());
	return cells;
}

function escapeTableCell(value) {
	return value.replaceAll("\\", "\\\\").replaceAll("|", "\\|").replaceAll("\n", " ");
}

function validateBodyMetadata(task, errors) {
	const targets = task.body.match(/^- \*\*Targets:\*\*\s*(.+)$/m);
	const tools = task.body.match(/^- \*\*Tools \/ APIs:\*\*\s*(.+)$/m);
	if (!targets?.[1]?.trim()) {
		errors.push(error("missing_targets", `Step ${task.id} must include '- **Targets:** ...'`, task.line));
	}
	if (!tools?.[1]?.trim()) {
		errors.push(error("missing_tools", `Step ${task.id} must include '- **Tools / APIs:** ...'`, task.line));
	}
}

function validateTitle(headings, errors) {
	const titleHeadings = headings.filter((heading) => heading.level === 1);
	if (titleHeadings.length !== 1 || titleHeadings[0].index !== 0 || !titleHeadings[0].text.trim()) {
		errors.push(error("invalid_title", "Plan must start with exactly one non-empty H1 title", titleHeadings[0]?.line));
	}
	return titleHeadings[0];
}

function validateSectionOrder(h2, required, errors) {
	if (h2.length !== required.length || h2.some((heading, index) => heading.text !== required[index])) {
		errors.push(error(
			"invalid_section_order",
			`Required H2 sections, in order: ${required.join("; ")}`,
			h2.find((heading, index) => heading.text !== required[index])?.line,
		));
	}
	const sectionByName = new Map(h2.map((heading) => [heading.text, heading]));
	for (const name of required) {
		if (!sectionByName.has(name)) errors.push(error("missing_section", `Missing section: ${name}`));
	}
	return sectionByName;
}

function parseStagesTable(content, startLine, steps, errors) {
	const tableBlocks = unfencedTableBlocks(content, startLine);
	if (tableBlocks.length !== 1 || tableBlocks[0].length < 3) {
		errors.push(error("invalid_stages", "Stages must contain exactly one contiguous, unfenced Markdown table", startLine));
		return [];
	}
	const tableRows = tableBlocks[0];
	const header = splitTableRow(tableRows[0].line);
	if (!header || header.map((cell) => cell.toLowerCase()).join("|") !== "stage|description|steps") {
		errors.push(error("invalid_stages", "Stages table header must be Stage, Description, Steps", tableRows[0].number));
	}
	const separator = splitTableRow(tableRows[1].line);
	if (!separator || separator.length !== 3 || separator.some((cell) => !/^:?-{3,}:?$/.test(cell))) {
		errors.push(error("invalid_stages", "Stages table separator is malformed", tableRows[1].number));
	}

	const knownSteps = new Set(steps.map((step) => step.id));
	const assignedSteps = new Set();
	const stages = [];
	for (const [index, row] of tableRows.slice(2).entries()) {
		const cells = splitTableRow(row.line);
		if (!cells || cells.length !== 3 || !/^\d+$/.test(cells[0]) || !cells[1] || !cells[2]) {
			errors.push(error("invalid_stage_row", "Each stage row needs a numeric ID, description, and step list", row.number));
			continue;
		}
		const [id, description, rawSteps] = cells;
		if (id !== String(index + 1)) {
			errors.push(error("stage_order", `Expected Stage ${index + 1}, found Stage ${id}`, row.number));
		}
		const stepIds = rawSteps.split(",").map((value) => value.trim()).filter(Boolean);
		if (stepIds.length === 0 || stepIds.some((stepId) => !/^\d+$/.test(stepId))) {
			errors.push(error("invalid_stage_steps", `Stage ${id} must list numeric step IDs separated by commas`, row.number));
		}
		for (const stepId of stepIds) {
			if (!knownSteps.has(stepId)) errors.push(error("unknown_step", `Stage ${id} references unknown Step ${stepId}`, row.number));
			if (assignedSteps.has(stepId)) errors.push(error("duplicate_step_assignment", `Step ${stepId} belongs to more than one stage`, row.number));
			assignedSteps.add(stepId);
		}
		stages.push({ id, description, stepIds });
	}
	for (const step of steps) {
		if (!assignedSteps.has(step.id)) errors.push(error("unassigned_step", `Step ${step.id} is not assigned to a stage`, step.line));
	}
	return stages;
}

function parseQuestionsAndAnswersTable(content, startLine, errors) {
	const tableBlocks = unfencedTableBlocks(content, startLine);
	const nonemptyRows = unfencedLineRows(content, startLine).filter((row) => row.line.trim());
	if (
		tableBlocks.length !== 1 || tableBlocks[0].length < 3 ||
		nonemptyRows.length !== tableBlocks[0].length
	) {
		errors.push(error(
			"invalid_questions_and_answers",
			"Questions & Answers must contain exactly one contiguous, unfenced Markdown table with at least one row",
			startLine,
		));
		return [];
	}
	const tableRows = tableBlocks[0];
	const header = splitTableRow(tableRows[0].line);
	if (!header || header.map((cell) => cell.toLowerCase()).join("|") !== "question|answer") {
		errors.push(error("invalid_questions_and_answers", "Questions & Answers table header must be Question, Answer", tableRows[0].number));
	}
	const separator = splitTableRow(tableRows[1].line);
	if (!separator || separator.length !== 2 || separator.some((cell) => !/^:?-{3,}:?$/.test(cell))) {
		errors.push(error("invalid_questions_and_answers", "Questions & Answers table separator is malformed", tableRows[1].number));
	}
	const questionsAndAnswers = [];
	for (const row of tableRows.slice(2)) {
		const cells = splitTableRow(row.line);
		if (!cells || cells.length !== 2 || !cells[0] || !cells[1]) {
			errors.push(error("invalid_question_answer_row", "Each Questions & Answers row needs a non-empty question and answer", row.number));
			continue;
		}
		questionsAndAnswers.push({ question: cells[0], answer: cells[1] });
	}
	return questionsAndAnswers;
}

function ownershipPathTokens(value) {
	return new Set(value.toLowerCase().match(/[a-z0-9_.-]+(?:\/[a-z0-9_.-]+)*\.[a-z0-9_-]+/g) ?? []);
}

function parseParallelExecutionTable(content, startLine, parts, errors) {
	const tableBlocks = unfencedTableBlocks(content, startLine);
	const nonemptyRows = unfencedLineRows(content, startLine).filter((row) => row.line.trim());
	if (
		tableBlocks.length !== 1 || tableBlocks[0].length < 3 ||
		nonemptyRows.length !== tableBlocks[0].length
	) {
		errors.push(error(
			"invalid_parallel_execution",
			"Parallel Execution must contain exactly one contiguous, unfenced Markdown table with at least one assignment",
			startLine,
		));
		return [];
	}
	const tableRows = tableBlocks[0];
	const header = splitTableRow(tableRows[0].line);
	if (!header || header.map((cell) => cell.toLowerCase()).join("|") !== "wave|worker|part|source part|depends on|ownership") {
		errors.push(error("invalid_parallel_execution", "Parallel Execution table header must be Wave, Worker, Part, Source Part, Depends On, Ownership", tableRows[0].number));
	}
	const separator = splitTableRow(tableRows[1].line);
	if (!separator || separator.length !== 6 || separator.some((cell) => !/^:?-{3,}:?$/.test(cell))) {
		errors.push(error("invalid_parallel_execution", "Parallel Execution table separator is malformed", tableRows[1].number));
	}

	const knownParts = new Set(parts.map((part) => part.id));
	const assignments = [];
	const assignedParts = new Set();
	const workers = new Set();
	const ownerships = new Map();
	let previousWave = 0;
	for (const row of tableRows.slice(2)) {
		const cells = splitTableRow(row.line);
		if (!cells || cells.length !== 6) {
			errors.push(error("invalid_parallel_execution_row", "Each Parallel Execution row needs six cells", row.number));
			continue;
		}
		const [rawWave, worker, partId, sourcePartId, rawDependencies, ownership] = cells;
		const wave = Number(rawWave);
		if (!Number.isInteger(wave) || wave < 1) {
			errors.push(error("invalid_parallel_wave", "Wave must be a positive integer", row.number));
		}
		if (wave > previousWave + 1) {
			errors.push(error("parallel_wave_gap", `Wave ${wave} follows Wave ${previousWave}; waves must be contiguous`, row.number));
		}
		if (wave < previousWave) {
			errors.push(error("parallel_wave_order", "Parallel Execution rows must be ordered by wave", row.number));
		}
		previousWave = Math.max(previousWave, wave);
		if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(worker)) {
			errors.push(error("invalid_parallel_worker", "Worker must be a non-empty identifier", row.number));
		}
		if (workers.has(worker)) errors.push(error("duplicate_parallel_worker", `Worker ${worker} owns more than one Part`, row.number));
		workers.add(worker);
		if (!knownParts.has(partId)) errors.push(error("unknown_parallel_part", `Parallel Execution references unknown Part ${partId}`, row.number));
		if (assignedParts.has(partId)) errors.push(error("duplicate_parallel_part", `Part ${partId} has more than one worker assignment`, row.number));
		assignedParts.add(partId);
		if (!/^[A-Z]+$/.test(sourcePartId)) {
			errors.push(error("invalid_source_part", "Source Part must be an uppercase Part identity", row.number));
		}
		const dependencies = rawDependencies === "—" ? [] : rawDependencies.split(",").map((value) => value.trim()).filter(Boolean);
		if (rawDependencies !== "—" && dependencies.length === 0) {
			errors.push(error("invalid_parallel_dependencies", "Depends On must be — or a comma-separated Part list", row.number));
		}
		if (!ownership) errors.push(error("missing_parallel_ownership", "Ownership must name an exclusive mutation boundary", row.number));
		const ownershipKey = ownership.toLowerCase().replace(/\s+/g, " ").trim();
		const paths = ownershipPathTokens(ownership);
		const overlap = [...ownerships.entries()].find(([key, prior]) =>
			key === ownershipKey || [...paths].some((path) => prior.paths.has(path)),
		);
		if (ownershipKey && overlap) {
			errors.push(error("overlapping_parallel_ownership", `Ownership overlaps Part ${overlap[1].partId}`, row.number));
		}
		if (ownershipKey) ownerships.set(ownershipKey, { partId, paths });
		assignments.push({ wave, worker, partId, sourcePartId, dependencies, ownership });
	}
	for (const part of parts) {
		if (!assignedParts.has(part.id)) errors.push(error("unassigned_parallel_part", `Part ${part.id} has no worker assignment`));
	}
	const assignmentByPart = new Map(assignments.map((assignment) => [assignment.partId, assignment]));
	for (const assignment of assignments) {
		for (const dependency of assignment.dependencies) {
			const predecessor = assignmentByPart.get(dependency);
			if (!predecessor) {
				errors.push(error("unknown_parallel_dependency", `Part ${assignment.partId} depends on unknown Part ${dependency}`));
			} else if (predecessor.wave >= assignment.wave) {
				errors.push(error("invalid_parallel_dependency", `Part ${assignment.partId} must depend only on an earlier wave`, undefined));
			}
		}
	}
	return assignments;
}

function parseVersion2Document(lines, headings, titleHeading, errors) {
	const h2 = headings.filter((heading) => heading.level === 2);
	const sectionByName = validateSectionOrder(h2, VERSION_2_REQUIRED_H2, errors);
	if (errors.some((item) => item.code === "invalid_section_order" || item.code === "missing_section")) {
		return { ok: false, errors };
	}

	const whyHeading = sectionByName.get("Why");
	const whatHeading = sectionByName.get("What");
	const stagesHeading = sectionByName.get("Stages");
	const why = contentBetween(lines, whyHeading.index + 1, whatHeading.index);
	if (!why) errors.push(error("empty_section", "Section cannot be empty: Why", whyHeading.line));

	const stepHeadings = headings.filter(
		(heading) => heading.level === 3 && heading.index > whatHeading.index && heading.index < stagesHeading.index,
	);
	const what = contentBetween(lines, whatHeading.index + 1, stepHeadings[0]?.index ?? stagesHeading.index);
	if (!what) errors.push(error("empty_section", "What must summarize the solution before its steps", whatHeading.line));
	if (stepHeadings.length === 0) errors.push(error("no_steps", "What must contain at least one executable step"));

	const unexpected = headings.filter((heading) => {
		if (heading.level === 4) return true;
		if (heading.level !== 3) return false;
		return !stepHeadings.includes(heading);
	});
	for (const heading of unexpected) {
		errors.push(error("unexpected_heading", `Unexpected heading: ${heading.text}`, heading.line));
	}

	const steps = [];
	const stepIds = new Set();
	for (const [index, heading] of stepHeadings.entries()) {
		const match = heading.text.match(/^Step (\d+) \[([^\]]+)\] (.+)$/);
		if (!match) {
			errors.push(error("malformed_step_heading", "Step headings must use '### Step N [status] Title'", heading.line));
			continue;
		}
		const [, id, status, title] = match;
		if (id !== String(index + 1)) errors.push(error("step_order", `Expected Step ${index + 1}, found Step ${id}`, heading.line));
		if (stepIds.has(id)) errors.push(error("duplicate_step", `Duplicate Step ${id}`, heading.line));
		stepIds.add(id);
		if (!STATUS_SET.has(status)) errors.push(error("invalid_status", `Step ${id} has invalid status '${status}'`, heading.line));
		const end = stepHeadings[index + 1]?.index ?? stagesHeading.index;
		const step = {
			id,
			status,
			title: title.trim(),
			body: contentBetween(lines, heading.index + 1, end),
			line: heading.line,
		};
		if (!step.body) errors.push(error("empty_step", `Step ${id} must have a body`, heading.line));
		validateBodyMetadata(step, errors);
		steps.push(step);
	}

	const stagesContent = contentBetween(lines, stagesHeading.index + 1, lines.length);
	const stages = parseStagesTable(stagesContent, stagesHeading.index + 2, steps, errors);
	if (stages.length === 0) errors.push(error("no_stages", "Plan must contain at least one stage"));
	if (errors.length > 0) return { ok: false, errors };

	const normalizedSteps = steps.map(({ line: _line, ...step }) => step);
	const stepById = new Map(normalizedSteps.map((step) => [step.id, step]));
	return {
		ok: true,
		document: {
			version: 2,
			title: titleHeading.text.trim(),
			why,
			what,
			steps: normalizedSteps,
			stages: stages.map((stage) => ({
				...stage,
				tasks: stage.stepIds.map((stepId) => stepById.get(stepId)),
			})),
		},
	};
}

function validateVersion3SectionOrder(h2, errors) {
	const sectionByName = new Map();
	let lastOrder = -1;
	for (const heading of h2) {
		const order = VERSION_3_H2.indexOf(heading.text);
		if (order < 0) {
			errors.push(error("invalid_section_order", `Unexpected H2 section: ${heading.text}`, heading.line));
			continue;
		}
		if (sectionByName.has(heading.text)) {
			errors.push(error("invalid_section_order", `Duplicate H2 section: ${heading.text}`, heading.line));
			continue;
		}
		if (order <= lastOrder) {
			errors.push(error(
				"invalid_section_order",
				`H2 sections must follow this order when present: ${VERSION_3_H2.join("; ")}`,
				heading.line,
			));
		}
		lastOrder = Math.max(lastOrder, order);
		sectionByName.set(heading.text, heading);
	}
	for (const name of VERSION_3_REQUIRED_H2) {
		if (!sectionByName.has(name)) errors.push(error("missing_section", `Missing section: ${name}`));
	}
	return sectionByName;
}

function parseVersion3Document(lines, headings, titleHeading, errors) {
	const h2 = headings.filter((heading) => heading.level === 2);
	const sectionByName = validateVersion3SectionOrder(h2, errors);
	if (errors.some((item) => item.code === "invalid_section_order" || item.code === "missing_section")) {
		return { ok: false, errors };
	}

	const sectionEnd = (heading) => h2.find((candidate) => candidate.index > heading.index)?.index ?? lines.length;
	const sectionContent = (name) => {
		const heading = sectionByName.get(name);
		return heading ? contentBetween(lines, heading.index + 1, sectionEnd(heading)) : undefined;
	};
	const backgroundHeading = sectionByName.get("Background");
	const changesHeading = sectionByName.get("Changes");
	const changesEnd = sectionEnd(changesHeading);
	const background = sectionContent("Background");
	if (!background) errors.push(error("empty_section", "Section cannot be empty: Background", backgroundHeading.line));

	const stepHeadings = headings.filter(
		(heading) => heading.level === 3 && heading.index > changesHeading.index && heading.index < changesEnd,
	);
	const changes = contentBetween(lines, changesHeading.index + 1, stepHeadings[0]?.index ?? changesEnd);
	if (!changes) errors.push(error("empty_section", "Changes must summarize the proposal before its steps", changesHeading.line));
	if (stepHeadings.length === 0) errors.push(error("no_steps", "Changes must contain at least one high-level step"));

	const unexpected = headings.filter((heading) => {
		if (heading.level === 4) return true;
		if (heading.level !== 3) return false;
		return !stepHeadings.includes(heading);
	});
	for (const heading of unexpected) errors.push(error("unexpected_heading", `Unexpected heading: ${heading.text}`, heading.line));

	const steps = [];
	const stepIds = new Set();
	for (const [index, heading] of stepHeadings.entries()) {
		const match = heading.text.match(/^Step (\d+) \[([^\]]+)\] (.+)$/);
		if (!match) {
			errors.push(error("malformed_step_heading", "Step headings must use '### Step N [status] Title'", heading.line));
			continue;
		}
		const [, id, status, title] = match;
		if (id !== String(index + 1)) errors.push(error("step_order", `Expected Step ${index + 1}, found Step ${id}`, heading.line));
		if (stepIds.has(id)) errors.push(error("duplicate_step", `Duplicate Step ${id}`, heading.line));
		stepIds.add(id);
		if (!STATUS_SET.has(status)) errors.push(error("invalid_status", `Step ${id} has invalid status '${status}'`, heading.line));
		const end = stepHeadings[index + 1]?.index ?? changesEnd;
		const step = {
			id,
			status,
			title: title.trim(),
			body: contentBetween(lines, heading.index + 1, end),
			line: heading.line,
		};
		if (!step.body) errors.push(error("empty_step", `Step ${id} must have a body`, heading.line));
		if (unfencedLineRows(step.body).some((row) => /^- \*\*(?:Targets|Tools \/ APIs):\*\*/.test(row.line))) {
			errors.push(error("disallowed_metadata", `Step ${id} must not list target files or tools/APIs`, heading.line));
		}
		steps.push(step);
	}

	const optionalContent = {};
	for (const [name, property] of [
		["Breaking Changes", "breakingChanges"],
		["Testing Plan", "testingPlan"],
		["Assumptions / Decisions", "assumptionsDecisions"],
	]) {
		if (!sectionByName.has(name)) continue;
		const value = sectionContent(name);
		if (!value) errors.push(error("empty_section", `Section cannot be empty: ${name}`, sectionByName.get(name).line));
		else optionalContent[property] = value;
	}

	const stagesHeading = sectionByName.get("Stages");
	const explicitStages = stagesHeading !== undefined;
	let stages;
	if (explicitStages) {
		const stagesContent = sectionContent("Stages");
		if (!stagesContent) errors.push(error("empty_section", "Section cannot be empty: Stages", stagesHeading.line));
		stages = parseStagesTable(stagesContent ?? "", stagesHeading.index + 2, steps, errors);
		if (stages.length === 0) errors.push(error("no_stages", "An explicit Stages section must contain at least one stage"));
	} else {
		stages = [{ id: "1", description: "Complete the planned changes.", stepIds: steps.map((step) => step.id) }];
	}
	if (errors.length > 0) return { ok: false, errors };

	const normalizedSteps = steps.map(({ line: _line, ...step }) => step);
	const stepById = new Map(normalizedSteps.map((step) => [step.id, step]));
	return {
		ok: true,
		document: {
			version: 3,
			title: titleHeading.text.trim(),
			background,
			changes,
			...optionalContent,
			steps: normalizedSteps,
			explicitStages,
			stages: stages.map((stage) => ({
				...stage,
				tasks: stage.stepIds.map((stepId) => stepById.get(stepId)),
			})),
		},
	};
}

function partIdForIndex(index) {
	let value = index + 1;
	let id = "";
	while (value > 0) {
		value -= 1;
		id = String.fromCharCode(65 + (value % 26)) + id;
		value = Math.floor(value / 26);
	}
	return id;
}

function validateVersion4SectionOrder(h2, errors) {
	const sectionByName = new Map();
	let lastOrder = -1;
	for (const heading of h2) {
		const order = VERSION_4_H2.indexOf(heading.text);
		if (order < 0) {
			errors.push(error(
				"unsupported_heading",
				`Unsupported H2 section '${heading.text}'. Allowed sections, in order: ${VERSION_4_H2.join("; ")}`,
				heading.line,
			));
			continue;
		}
		if (sectionByName.has(heading.text)) {
			errors.push(error("duplicate_section", `Duplicate H2 section: ${heading.text}`, heading.line));
			continue;
		}
		if (order <= lastOrder) {
			errors.push(error(
				"invalid_section_order",
				`H2 sections must follow this order when present: ${VERSION_4_H2.join("; ")}`,
				heading.line,
			));
		}
		lastOrder = Math.max(lastOrder, order);
		sectionByName.set(heading.text, heading);
	}
	for (const name of VERSION_4_REQUIRED_H2) {
		if (!sectionByName.has(name)) errors.push(error("missing_section", `Missing required section: ${name}`));
	}
	return sectionByName;
}

function parsePartLedger(body, partId, line, errors, allowManagedMetadata) {
	const rows = unfencedLineRows(body, line);
	const ledgerRows = rows.filter((row) => /^- \*\*Ledger:\*\*/.test(row.line));
	if (ledgerRows.length === 0) return "pending";
	if (ledgerRows.length > 1) {
		errors.push(error("duplicate_managed_metadata", `Part ${partId} contains more than one managed Ledger row`, ledgerRows[1].number));
		return "pending";
	}
	if (!allowManagedMetadata) {
		errors.push(error("managed_metadata_forbidden", `Part ${partId} must not contain author-written Ledger metadata`, ledgerRows[0].number));
		return "pending";
	}
	const raw = ledgerRows[0].line.replace(/^- \*\*Ledger:\*\*\s*/, "");
	try {
		const ledger = JSON.parse(raw);
		if (!ledger || typeof ledger !== "object" || !STATUS_SET.has(ledger.status)) throw new Error("invalid status");
		return ledger.status;
	} catch {
		errors.push(error("invalid_managed_metadata", `Part ${partId} has malformed extension-managed Ledger metadata`, ledgerRows[0].number));
		return "pending";
	}
}

function parseVersion4Document(lines, headings, titleHeading, errors, options) {
	const h2 = headings.filter((heading) => heading.level === 2);
	const sectionByName = validateVersion4SectionOrder(h2, errors);
	if (errors.some((item) => ["unsupported_heading", "duplicate_section", "invalid_section_order", "missing_section"].includes(item.code))) {
		return { ok: false, errors };
	}

	const sectionEnd = (heading) => h2.find((candidate) => candidate.index > heading.index)?.index ?? lines.length;
	const sectionContent = (name) => {
		const heading = sectionByName.get(name);
		return heading ? contentBetween(lines, heading.index + 1, sectionEnd(heading)) : undefined;
	};
	const contextHeading = sectionByName.get("Context");
	const approachHeading = sectionByName.get("Approach");
	const approachEnd = sectionEnd(approachHeading);
	const context = sectionContent("Context");
	if (!context) errors.push(error("empty_section", "Required section cannot be empty: Context", contextHeading.line));

	const optionalContent = {};
	const questionsAndAnswersHeading = sectionByName.get("Questions & Answers");
	if (questionsAndAnswersHeading) {
		const questionsAndAnswers = parseQuestionsAndAnswersTable(
			sectionContent("Questions & Answers"),
			questionsAndAnswersHeading.index + 2,
			errors,
		);
		if (questionsAndAnswers.length > 0) optionalContent.questionsAndAnswers = questionsAndAnswers;
	}

	const partHeadings = headings.filter(
		(heading) => heading.level === 3 && heading.index > approachHeading.index && heading.index < approachEnd,
	);
	const approach = contentBetween(lines, approachHeading.index + 1, partHeadings[0]?.index ?? approachEnd);
	if (!approach) errors.push(error("empty_section", "Approach must explain the solution before its Parts", approachHeading.line));
	if (partHeadings.length === 0) errors.push(error("no_parts", "Approach must contain at least one ordered Part"));

	const unexpected = headings.filter((heading) => {
		if (heading.level >= 4) return true;
		if (heading.level !== 3) return false;
		return !partHeadings.includes(heading);
	});
	for (const heading of unexpected) {
		errors.push(error(
			"unsupported_heading",
			`Unsupported heading '${heading.text}'. Version 4 allows only Part headings below H2 sections`,
			heading.line,
		));
	}

	const parts = [];
	const partIds = new Set();
	for (const [index, heading] of partHeadings.entries()) {
		const match = heading.text.match(/^Part ([A-Z]+) — (.+)$/);
		if (!match) {
			errors.push(error("malformed_part_heading", "Part headings must use '### Part A — Action-oriented title' without a status marker", heading.line));
			continue;
		}
		const [, id, rawTitle] = match;
		const expectedId = partIdForIndex(index);
		if (id !== expectedId) errors.push(error("part_order", `Expected Part ${expectedId}, found Part ${id}`, heading.line));
		if (partIds.has(id)) errors.push(error("duplicate_part", `Duplicate Part ${id}`, heading.line));
		partIds.add(id);
		const title = rawTitle.trim();
		if (!title) errors.push(error("empty_part_title", `Part ${id} must have an action-oriented title`, heading.line));
		const end = partHeadings[index + 1]?.index ?? approachEnd;
		const body = contentBetween(lines, heading.index + 1, end);
		if (!body) errors.push(error("empty_part", `Part ${id} must have a body`, heading.line));
		if (unfencedLineRows(body, heading.line + 1).some((row) => /^- \*\*(?:Targets|Tools \/ APIs):\*\*/.test(row.line))) {
			errors.push(error("disallowed_metadata", `Part ${id} must not reintroduce mandatory target or tool inventory metadata`, heading.line));
		}
		const status = parsePartLedger(body, id, heading.line + 1, errors, options.allowManagedMetadata !== false);
		parts.push({ id, status, title, body });
	}

	const parallelExecutionHeading = sectionByName.get("Parallel Execution");
	if (parallelExecutionHeading) {
		const assignments = parseParallelExecutionTable(
			sectionContent("Parallel Execution"),
			parallelExecutionHeading.index + 2,
			parts,
			errors,
		);
		if (assignments.length > 0) optionalContent.parallelExecution = assignments;
	}

	for (const [name, property] of [["Critical Files", "criticalFiles"], ["Verification", "verification"]]) {
		if (!sectionByName.has(name)) continue;
		const value = sectionContent(name);
		if (!value) errors.push(error("empty_section", `Optional section cannot be empty when present: ${name}`, sectionByName.get(name).line));
		else optionalContent[property] = value;
	}
	if (errors.length > 0) return { ok: false, errors };

	const assignmentByPart = new Map(optionalContent.parallelExecution?.map((assignment) => [assignment.partId, assignment]));
	return {
		ok: true,
		document: {
			version: PLAN_DOCUMENT_VERSION,
			title: titleHeading.text.trim(),
			context,
			approach,
			...optionalContent,
			parts,
			stages: parts.map((part) => ({
				id: part.id,
				description: part.title,
				stepIds: [part.id],
				tasks: [part],
				...(assignmentByPart.get(part.id) ? { parallelExecution: assignmentByPart.get(part.id) } : {}),
			})),
		},
	};
}

function parseLegacyOverview(content, startLine, errors) {
	const tableBlocks = unfencedTableBlocks(content, startLine);
	if (tableBlocks.length !== 1 || tableBlocks[0].length < 3) {
		errors.push(error("invalid_overview", "Stages Overview must contain exactly one contiguous, unfenced Markdown table", startLine));
		return [];
	}
	const tableRows = tableBlocks[0];
	const header = splitTableRow(tableRows[0].line);
	if (!header || header.map((cell) => cell.toLowerCase()).join("|") !== "stage|name|purpose") {
		errors.push(error("invalid_overview", "Stages Overview table header must be Stage, Name, Purpose", tableRows[0].number));
	}
	const separator = splitTableRow(tableRows[1].line);
	if (!separator || separator.length !== 3 || separator.some((cell) => !/^:?-{3,}:?$/.test(cell))) {
		errors.push(error("invalid_overview", "Stages Overview table separator is malformed", tableRows[1].number));
	}
	const stages = [];
	const seen = new Set();
	for (const row of tableRows.slice(2)) {
		const cells = splitTableRow(row.line);
		if (!cells || cells.length !== 3 || !/^\d+$/.test(cells[0]) || !cells[1] || !cells[2]) {
			errors.push(error("invalid_overview_row", "Each stage row needs a numeric ID, name, and purpose", row.number));
			continue;
		}
		if (seen.has(cells[0])) {
			errors.push(error("duplicate_stage", `Duplicate stage ID ${cells[0]} in overview`, row.number));
			continue;
		}
		seen.add(cells[0]);
		stages.push({ id: cells[0], name: cells[1], purpose: cells[2] });
	}
	return stages;
}

function parseLegacyDocument(lines, headings, titleHeading, errors) {
	const h2 = headings.filter((heading) => heading.level === 2);
	const sectionByName = validateSectionOrder(h2, LEGACY_REQUIRED_H2, errors);
	if (errors.some((item) => item.code === "invalid_section_order" || item.code === "missing_section")) {
		return { ok: false, errors };
	}

	const sectionContent = {};
	for (let index = 0; index < h2.length; index += 1) {
		const heading = h2[index];
		const end = h2[index + 1]?.index ?? lines.length;
		sectionContent[heading.text] = contentBetween(lines, heading.index + 1, end);
		if (!sectionContent[heading.text]) errors.push(error("empty_section", `Section cannot be empty: ${heading.text}`, heading.line));
	}

	const overviewHeading = sectionByName.get("Stages Overview");
	const stagesEnd = sectionByName.get("Conditional Logic and Edge Cases").index;
	const stageHeadings = headings.filter(
		(heading) => heading.level === 3 && heading.index > overviewHeading.index && heading.index < stagesEnd,
	);
	const overviewEnd = stageHeadings[0]?.index ?? stagesEnd;
	const overview = parseLegacyOverview(contentBetween(lines, overviewHeading.index + 1, overviewEnd), overviewHeading.index + 2, errors);
	for (const heading of headings.filter((item) => item.level === 3 && !stageHeadings.includes(item))) {
		errors.push(error("unexpected_heading", `Unexpected H3 heading: ${heading.text}`, heading.line));
	}
	if (stageHeadings.length === 0) errors.push(error("no_stages", "Plan must contain at least one stage section"));

	const stages = [];
	const taskIds = new Set();
	for (let stageIndex = 0; stageIndex < stageHeadings.length; stageIndex += 1) {
		const heading = stageHeadings[stageIndex];
		const match = heading.text.match(/^Stage (\d+) — (.+)$/);
		if (!match) {
			errors.push(error("malformed_stage_heading", "Stage headings must use '### Stage N — Name'", heading.line));
			continue;
		}
		const [, id, name] = match;
		if (id !== String(stageIndex + 1)) errors.push(error("stage_order", `Expected Stage ${stageIndex + 1}, found Stage ${id}`, heading.line));
		const end = stageHeadings[stageIndex + 1]?.index ?? stagesEnd;
		const taskHeadings = headings.filter((item) => item.level === 4 && item.index > heading.index && item.index < end);
		const tasks = [];
		for (let taskIndex = 0; taskIndex < taskHeadings.length; taskIndex += 1) {
			const taskHeading = taskHeadings[taskIndex];
			const taskMatch = taskHeading.text.match(/^(\d+)\.(\d+) \[([^\]]+)\] (.+)$/);
			if (!taskMatch) {
				errors.push(error("malformed_task_heading", "Task headings must use '#### N.M [status] Title'", taskHeading.line));
				continue;
			}
			const [, taskStage, taskNumber, status, taskTitle] = taskMatch;
			const taskId = `${taskStage}.${taskNumber}`;
			if (taskStage !== id || Number(taskNumber) !== taskIndex + 1) errors.push(error("task_order", `Expected task ${id}.${taskIndex + 1}, found ${taskId}`, taskHeading.line));
			if (!STATUS_SET.has(status)) errors.push(error("invalid_status", `Task ${taskId} has invalid status '${status}'`, taskHeading.line));
			if (taskIds.has(taskId)) errors.push(error("duplicate_task", `Duplicate task ID ${taskId}`, taskHeading.line));
			taskIds.add(taskId);
			const taskEnd = taskHeadings[taskIndex + 1]?.index ?? end;
			const task = { id: taskId, stageId: id, status, title: taskTitle.trim(), body: contentBetween(lines, taskHeading.index + 1, taskEnd), line: taskHeading.line };
			if (!task.body) errors.push(error("empty_task", `Task ${taskId} must have a body`, taskHeading.line));
			validateBodyMetadata(task, errors);
			tasks.push(task);
		}
		if (tasks.length === 0) errors.push(error("empty_stage", `Stage ${id} has no executable tasks`, heading.line));
		stages.push({ id, name: name.trim(), tasks });
	}

	if (overview.length !== stages.length) errors.push(error("stage_mismatch", "Stages Overview and stage sections must contain the same stages"));
	for (let index = 0; index < Math.min(overview.length, stages.length); index += 1) {
		if (overview[index].id !== stages[index].id || overview[index].name !== stages[index].name) errors.push(error("stage_mismatch", `Overview row ${index + 1} does not match its stage section`));
	}
	if (taskIds.size === 0) errors.push(error("no_tasks", "Plan must contain at least one executable task"));
	if (errors.length > 0) return { ok: false, errors };

	return {
		ok: true,
		document: {
			version: 1,
			title: titleHeading.text.trim(),
			objective: sectionContent["Objective / Goal Statement"],
			stages: stages.map((stage, index) => ({
				...stage,
				purpose: overview[index].purpose,
				description: overview[index].purpose,
				stepIds: stage.tasks.map((task) => task.id),
				tasks: stage.tasks.map(({ line: _line, ...task }) => task),
			})),
			conditionalLogic: sectionContent["Conditional Logic and Edge Cases"],
			parallelSubagents: sectionContent["Parallel Subagent Recommendations"],
			testingRequirements: sectionContent["Testing Requirements and Edge Cases"],
			stoppingCriteria: sectionContent["Stopping Criteria / Guardrails"],
		},
	};
}

export function parsePlanDocument(markdown, options = {}) {
	const maxBytes = options.maxBytes ?? MAX_PLAN_BYTES;
	if (typeof markdown !== "string") return { ok: false, errors: [error("invalid_input", "Plan must be a Markdown string")] };
	if (Buffer.byteLength(markdown, "utf8") > maxBytes) return { ok: false, errors: [error("plan_too_large", `Plan exceeds the ${maxBytes}-byte limit`)] };
	let split;
	try {
		split = splitManagedProgressReport(markdown);
	} catch (reportError) {
		return { ok: false, errors: [error(reportError.code ?? "malformed_progress_report", reportError.message)] };
	}
	const normalized = split.coreMarkdown.trim();
	if (!normalized) return { ok: false, errors: [error("empty_plan", "Plan cannot be empty")] };

	const lines = normalized.split("\n");
	const headings = scanHeadings(lines);
	const errors = [];
	const titleHeading = validateTitle(headings, errors);
	if (!titleHeading) return { ok: false, errors };
	const h2Texts = headings.filter((heading) => heading.level === 2).map((heading) => heading.text);
	let result;
	if (h2Texts.some((text) => LEGACY_REQUIRED_H2.includes(text))) {
		result = parseLegacyDocument(lines, headings, titleHeading, errors);
	} else if (h2Texts.includes("Why") || h2Texts.includes("What")) {
		result = parseVersion2Document(lines, headings, titleHeading, errors);
	} else if (h2Texts.some((text) => VERSION_4_H2.includes(text))) {
		result = parseVersion4Document(lines, headings, titleHeading, errors, options);
	} else {
		result = parseVersion3Document(lines, headings, titleHeading, errors);
	}
	if (result.ok && split.report) {
		const expectedHeading = result.document.version === PLAN_DOCUMENT_VERSION
			? PART_PROGRESS_REPORT_HEADING
			: PROGRESS_REPORT_HEADING;
		if (split.report.heading !== expectedHeading) {
			return {
				ok: false,
				errors: [error(
					"invalid_progress_heading",
					`Document version ${result.document.version} requires managed heading '${expectedHeading}'`,
				)],
			};
		}
		result.document.managedProgressReport = true;
	}
	return result;
}

function renderVersion2Document(document) {
	const lines = [
		`# ${document.title.trim()}`,
		"",
		"## Why",
		"",
		document.why.trim(),
		"",
		"## What",
		"",
		document.what.trim(),
	];
	for (const step of document.steps) {
		lines.push("", `### Step ${step.id} [${step.status}] ${step.title}`, "", step.body.trim());
	}
	lines.push("", "## Stages", "", "| Stage | Description | Steps |", "|---|---|---|");
	for (const stage of document.stages) {
		lines.push(`| ${stage.id} | ${escapeTableCell(stage.description)} | ${stage.stepIds.join(", ")} |`);
	}
	lines.push("");
	return lines.join("\n");
}

function renderVersion3Document(document) {
	const lines = [
		`# ${document.title.trim()}`,
		"",
		"## Background",
		"",
		document.background.trim(),
		"",
		"## Changes",
	];
	if (document.changes?.trim()) lines.push("", document.changes.trim());
	for (const step of document.steps) {
		lines.push("", `### Step ${step.id} [${step.status}] ${step.title}`, "", step.body.trim());
	}
	for (const [heading, property] of [
		["Breaking Changes", "breakingChanges"],
		["Testing Plan", "testingPlan"],
		["Assumptions / Decisions", "assumptionsDecisions"],
	]) {
		if (document[property]?.trim()) lines.push("", `## ${heading}`, "", document[property].trim());
	}
	if (document.explicitStages) {
		lines.push("", "## Stages", "", "| Stage | Description | Steps |", "|---|---|---|");
		for (const stage of document.stages) {
			lines.push(`| ${stage.id} | ${escapeTableCell(stage.description)} | ${stage.stepIds.join(", ")} |`);
		}
	}
	lines.push("");
	return lines.join("\n");
}

function renderVersion4Document(document) {
	const lines = [
		`# ${document.title.trim()}`,
		"",
		"## Context",
		"",
		document.context.trim(),
	];
	if (document.questionsAndAnswers?.length) {
		lines.push("", "## Questions & Answers", "", "| Question | Answer |", "|---|---|");
		for (const { question, answer } of document.questionsAndAnswers) {
			lines.push(`| ${escapeTableCell(question)} | ${escapeTableCell(answer)} |`);
		}
	}
	lines.push("", "## Approach");
	if (document.approach?.trim()) lines.push("", document.approach.trim());
	for (const part of document.parts) {
		const body = part.body.trim();
		lines.push("", `### Part ${part.id} — ${part.title}`);
		if (body.startsWith("- **Ledger:**")) lines.push(body);
		else lines.push("", body);
	}
	if (document.parallelExecution?.length) {
		lines.push("", "## Parallel Execution", "", "| Wave | Worker | Part | Source Part | Depends On | Ownership |", "|---|---|---|---|---|---|");
		for (const assignment of document.parallelExecution) {
			lines.push(`| ${assignment.wave} | ${escapeTableCell(assignment.worker)} | ${assignment.partId} | ${assignment.sourcePartId} | ${assignment.dependencies.length ? assignment.dependencies.join(", ") : "—"} | ${escapeTableCell(assignment.ownership)} |`);
		}
	}
	for (const [heading, property] of [["Critical Files", "criticalFiles"], ["Verification", "verification"]]) {
		if (document[property]?.trim()) lines.push("", `## ${heading}`, "", document[property].trim());
	}
	lines.push("");
	return lines.join("\n");
}

function renderLegacyDocument(document) {
	const lines = [
		`# ${document.title.trim()}`,
		"",
		"## Objective / Goal Statement",
		"",
		document.objective.trim(),
		"",
		"## Stages Overview",
		"",
		"| Stage | Name | Purpose |",
		"|---|---|---|",
	];
	for (const stage of document.stages) lines.push(`| ${stage.id} | ${escapeTableCell(stage.name)} | ${escapeTableCell(stage.purpose)} |`);
	for (const stage of document.stages) {
		lines.push("", `### Stage ${stage.id} — ${stage.name}`);
		for (const task of stage.tasks) lines.push("", `#### ${task.id} [${task.status}] ${task.title}`, "", task.body.trim());
	}
	lines.push(
		"", "## Conditional Logic and Edge Cases", "", document.conditionalLogic.trim(),
		"", "## Parallel Subagent Recommendations", "", document.parallelSubagents.trim(),
		"", "## Testing Requirements and Edge Cases", "", document.testingRequirements.trim(),
		"", "## Stopping Criteria / Guardrails", "", document.stoppingCriteria.trim(), "",
	);
	return lines.join("\n");
}

export function renderPlanDocument(document) {
	let rendered;
	if (document.version === 1) rendered = renderLegacyDocument(document);
	else if (document.version === 2) rendered = renderVersion2Document(document);
	else if (document.version === 3) rendered = renderVersion3Document(document);
	else rendered = renderVersion4Document(document);
	return document.managedProgressReport
		? replaceManagedProgressReport(rendered, buildDocumentProgressRows(document))
		: rendered;
}

function normalizeEquivalentContent(value) {
	return value
		.replaceAll("\r\n", "\n")
		.replaceAll("\r", "\n")
		.split("\n")
		.filter((line) => !/^- \*\*Ledger:\*\*/.test(line))
		.join("\n")
		.replace(/\s+/g, " ")
		.trim();
}

function equivalentValue(value) {
	if (Array.isArray(value)) return JSON.stringify(value);
	return normalizeEquivalentContent(value ?? "");
}

export function validateFastPlanRevision(sourceMarkdown, optimizedMarkdown) {
	const source = parsePlanDocument(sourceMarkdown);
	const optimized = parsePlanDocument(optimizedMarkdown);
	const errors = [];
	if (!source.ok) errors.push(...source.errors.map((item) => ({ ...item, code: `invalid_source_${item.code}` })));
	if (!optimized.ok) errors.push(...optimized.errors.map((item) => ({ ...item, code: `invalid_optimized_${item.code}` })));
	if (errors.length > 0) return { ok: false, errors };
	if (source.document.version !== PLAN_DOCUMENT_VERSION || optimized.document.version !== PLAN_DOCUMENT_VERSION) {
		return { ok: false, errors: [error("fast_revision_requires_version_4", "Fast revisions require version-4 Part plans")] };
	}
	if (!optimized.document.parallelExecution?.length) {
		return { ok: false, errors: [error("missing_parallel_execution", "Fast revisions must include a Parallel Execution schedule")] };
	}
	for (const property of ["title", "context", "questionsAndAnswers", "approach", "criticalFiles", "verification"]) {
		if (equivalentValue(source.document[property]) !== equivalentValue(optimized.document[property])) {
			errors.push(error("fast_revision_scope_changed", `Fast revision changed ${property}`));
		}
	}
	const sourcePartOrder = new Map(source.document.parts.map((part, index) => [part.id, index]));
	const optimizedBySource = new Map();
	let previousSourceIndex = -1;
	for (const part of optimized.document.parts) {
		const assignment = optimized.document.parallelExecution.find((candidate) => candidate.partId === part.id);
		if (!assignment || !sourcePartOrder.has(assignment.sourcePartId)) {
			errors.push(error("unknown_fast_revision_source_part", `Part ${part.id} must map to one source Part`));
			continue;
		}
		const sourceIndex = sourcePartOrder.get(assignment.sourcePartId);
		if (sourceIndex < previousSourceIndex) {
			errors.push(error("fast_revision_source_order", "Optimized Parts must remain in source Part order"));
		}
		previousSourceIndex = Math.max(previousSourceIndex, sourceIndex);
		const mapped = optimizedBySource.get(assignment.sourcePartId) ?? [];
		mapped.push(part);
		optimizedBySource.set(assignment.sourcePartId, mapped);
	}
	for (const sourcePart of source.document.parts) {
		const mapped = optimizedBySource.get(sourcePart.id);
		if (!mapped?.length) {
			errors.push(error("missing_fast_revision_source_part", `Source Part ${sourcePart.id} has no mapped optimized Part`));
			continue;
		}
		const optimizedBody = mapped.map((part) => part.body).join("\n\n");
		if (normalizeEquivalentContent(sourcePart.body) !== normalizeEquivalentContent(optimizedBody)) {
			errors.push(error("fast_revision_part_scope_changed", `Mapped Parts changed the approved body of source Part ${sourcePart.id}`));
		}
	}
	return errors.length > 0 ? { ok: false, errors } : { ok: true, source: source.document, optimized: optimized.document };
}

export function validatePlanDocument(markdown, options) {
	const result = parsePlanDocument(markdown, options);
	return result.ok ? [] : result.errors;
}
